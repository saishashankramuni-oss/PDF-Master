const isLocalhost = Boolean(
  window.location.hostname === 'localhost' ||
    window.location.hostname === '[::1]' ||
    window.location.hostname.match(
      /^127\.(.*)$/
    )
)

// This function receives the registration details and
// loads the correct implementation to finish a PWA's
// onboarding experience.
function registerValidSW(swUrl, successCallback, failedCallback) {
  navigator.serviceWorker
    .register(swUrl)
    .then(() => {
      // Check if the browser supports the beforeinstallprompt event
      let success = false
      if (window.deferredInstallPrompt) {
        // The events can only be fired once, so we
        // need to keep track of the deffered prompt
        success = true
      } else {
        // Chrome 68+, Firefox, and Opera support the
        // install event. Safari is still working on it.
        success = true
      }
      if (successCallback) {
        successCallback(success)
      }
    })
    .catch(error => {
      console.error('Error registering service worker:', error)
      if (failedCallback) {
        failedCallback(error)
      }
    })
}

// This function is just like registerValidSW(), but it will
// also listen for the `install` event, and
function registerWithSW(swUrl, onInstallReady, onNotSupported) {
  registerValidSW(swUrl, (success) => {
    if (success) {
      // At this point, the service worker is active.
      // You can optionally log a message to console
      // or take any other action.
      onInstallReady()
    } else {
      onNotSupported()
    }
  }, onNotSupported)
}

// Make sure the service worker hasn't already been registered
// (in case the user reloads the page)
function registerServiceWorker() {
  if (process.env.NODE_ENV === 'production' && 'serviceWorker' in navigator) {
    // The URL for the service worker script is generated by the build
    // and can be found in the generated service-worker.js file.
    const swUrl = process.env.PUBLIC_URL + '/service-worker.js'

    if (isLocalhost) {
      // This is running on localhost. Let's check if a service worker's
      // global scope is already defined.
      navigator.serviceWorker.getRegistration().then(registration => {
        if (registration) {
          registration.unregister().then(() => {
            // After unregistering, we refresh the page to load the
            // fresh markup and scripts.
            window.location.reload()
          })
        }
        // If no registration, we'll just register the service worker
        registerWithSW(
          swUrl,
          // onInstallReady
          () => console.log('Service worker registered successfully.')
        )
      })
    } else {
      // Not localHost, just register the service worker
      registerWithSW(
        swUrl,
        // onInstallReady
        () => console.log('Service worker registered successfully.')
      )
    }
  }
}

export { registerServiceWorker }